"""Emit transparent Lean data and proofs for the finite affine profile.

The generated file verifies every breakpoint cell by endpoint inequalities.
It does not infer correctness over an interval merely by sampling its midpoint.
The relationship between this profile and the determinant's arithmetic rate
remains a separate mathematical obligation.
"""
from fractions import Fraction as F
from pathlib import Path
import json

BASE = Path(__file__).resolve().parents[1]
S, RHO, DELTA = F(1, 20), F(5, 4), F(6, 5)
LEFT, RIGHT = F(1, 40), F(9, 20)


def rat(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else f"({x.numerator} / {x.denominator})"


points = {LEFT, RIGHT}
for q in range(1, 41):
    points.update((F(1, q), F(2, 2*q+1)))
for k in range(1, 102):
    points.add(2*RHO/k)
points = sorted(x for x in points if LEFT <= x <= RIGHT)
cells = []
for a,b in zip(points,points[1:]):
    mid = (a+b)/2
    q = 1 // mid
    e = int(2*(1-q*mid) >= mid)
    d = (2*RHO) // mid
    crossing = (d+1-DELTA)/((d+1)*(q+F(e,2)))
    cuts = [a,crossing,b] if a < crossing < b else [a,b]
    for lo,hi in zip(cuts,cuts[1:]):
        saturated = (d+1)*(1-(q+F(e,2))*(lo+hi)/2) >= DELTA
        intercept = (5+e)*DELTA if saturated else (4+e)*DELTA+d+1
        slope = F(0) if saturated else -(d+1)*(q+F(e,2))
        area = (hi-lo)*(intercept+slope*(lo+hi)/2)
        assert lo > 0 and lo < hi
        assert q*hi <= 1 <= (q+1)*lo
        assert (2*q+1)*hi <= 2 if e else 2 <= (2*q+1)*lo
        assert d*hi <= 2*RHO <= (d+1)*lo
        assert DELTA <= (d+1)*(1-(q+F(e,2))*hi) if saturated else (d+1)*(1-(q+F(e,2))*lo) <= DELTA
        cells.append((lo,hi,q,e,d,saturated,area))
assert len(cells)==228

header = '''import Zeta5.Certificate.Constants
import Mathlib.Data.List.Pairwise

/-!
# Kernel-checkable finite arithmetic profile

Generated by `scripts/generate_arithmetic_cells.py` from the manuscript's
exact rational breakpoint formulas. Every cell checks endpoint inequalities
for all three floor/branch selections. No native evaluation oracle is used.
This file does not prove that the profile bounds a determinant valuation.
-/

namespace Zeta5.Certificate

structure ArithmeticCell where
  lo : ℚ
  hi : ℚ
  q : ℕ
  epsilon : Bool
  degree : ℕ
  saturated : Bool

namespace ArithmeticCell

def eps (c : ArithmeticCell) : ℚ := if c.epsilon then 1 else 0
def widthSlope (c : ArithmeticCell) : ℚ := c.q + c.eps / 2
def intercept (c : ArithmeticCell) : ℚ :=
  if c.saturated then (5 + c.eps) * delta else (4 + c.eps) * delta + c.degree + 1
def slope (c : ArithmeticCell) : ℚ :=
  if c.saturated then 0 else -(c.degree + 1) * c.widthSlope
def area (c : ArithmeticCell) : ℚ :=
  (c.hi - c.lo) * (c.intercept + c.slope * (c.lo + c.hi) / 2)

/-- Endpoint checks certify the selected affine branches on the open cell. -/
def Valid (c : ArithmeticCell) : Prop :=
  0 < c.lo ∧ c.lo < c.hi ∧
  (c.q : ℚ) * c.hi ≤ 1 ∧ 1 ≤ (c.q + 1 : ℚ) * c.lo ∧
  (if c.epsilon then (2 * c.q + 1 : ℚ) * c.hi ≤ 2
   else 2 ≤ (2 * c.q + 1 : ℚ) * c.lo) ∧
  (c.degree : ℚ) * c.hi ≤ 2 * rho ∧ 2 * rho ≤ (c.degree + 1 : ℚ) * c.lo ∧
  (if c.saturated then delta ≤ (c.degree + 1 : ℚ) * (1 - c.widthSlope * c.hi)
   else (c.degree + 1 : ℚ) * (1 - c.widthSlope * c.lo) ≤ delta)

end ArithmeticCell

'''
lines=[header]
for j,(lo,hi,q,e,d,saturated,area) in enumerate(cells):
    name=f"arithmeticCell{j:03}"
    lines.append(f"def {name} : ArithmeticCell := ⟨{rat(lo)}, {rat(hi)}, {q}, {str(bool(e)).lower()}, {d}, {str(saturated).lower()}⟩\n")
    lines.append(f"theorem {name}_valid : {name}.Valid := by\n  norm_num [ArithmeticCell.Valid, ArithmeticCell.widthSlope, ArithmeticCell.eps, {name}, delta, rho, s]\n")
    lines.append(f"theorem {name}_area : {name}.area = {rat(area)} := by\n  norm_num [ArithmeticCell.area, ArithmeticCell.intercept, ArithmeticCell.slope, ArithmeticCell.widthSlope, ArithmeticCell.eps, {name}, delta, rho, s]\n")
lines.append("def arithmeticCells : List ArithmeticCell := [\n"+",\n".join(f"  arithmeticCell{j:03}" for j in range(len(cells)))+"]\n")
lines.append("theorem arithmeticCells_length : arithmeticCells.length = 228 := by rfl\n")
lines.append("set_option maxRecDepth 4096 in\nset_option maxHeartbeats 4000000 in\ntheorem arithmeticCells_all_valid : ∀ c ∈ arithmeticCells, c.Valid := by\n  unfold arithmeticCells\n  "+"\n  ".join(f"refine List.forall_mem_cons.mpr ⟨arithmeticCell{j:03}_valid, ?_⟩" for j in range(len(cells)))+"\n  simp\n")
for j in range(len(cells)-1):
    lines.append(f"theorem arithmeticCell{j:03}_next : arithmeticCell{j:03}.hi = arithmeticCell{j+1:03}.lo := by rfl\n")
lines.append("theorem arithmeticCells_first : arithmeticCell000.lo = 1 / 40 := by rfl\n")
lines.append("theorem arithmeticCells_last : arithmeticCell227.hi = 9 / 20 := by rfl\n")

areas=sum((x[-1] for x in cells),F(0))
lines.append(f"def middleArea : ℚ := {rat(areas)}\n")
for block in range((len(cells)+15)//16):
    ids=list(range(16*block,min(16*(block+1),len(cells))))
    area=sum((cells[j][-1] for j in ids),F(0))
    lines.append(f"def middleAreaBlock{block:02} : ℚ := "+" + ".join(f"arithmeticCell{j:03}.area" for j in ids)+"\n")
    lines.append(f"theorem middleAreaBlock{block:02}_exact : middleAreaBlock{block:02} = {rat(area)} := by\n  unfold middleAreaBlock{block:02}\n  rw ["+", ".join(f"arithmeticCell{j:03}_area" for j in ids)+"]\n  norm_num\n")
lines.append("theorem middleArea_blocks : "+" + ".join(f"middleAreaBlock{block:02}" for block in range(15))+" = middleArea := by\n  rw ["+", ".join(f"middleAreaBlock{block:02}_exact" for block in range(15))+"]\n  norm_num [middleArea]\n")
lines.append("theorem arithmeticTotal_decomposition :\n    (969 : ℚ) / 6400 + 19 / 16 + 901 / 600 + middleArea = arithmeticTotal := by\n  norm_num [middleArea, arithmeticTotal]\n")
lines.append("\nend Zeta5.Certificate\n")
out=BASE/'Zeta5/Certificate/ArithmeticCells.lean'
out.write_text('\n'.join(lines))
(BASE/'evidence/arithmetic_cells.json').write_text(json.dumps([{'lo':str(a),'hi':str(b),'q':q,'epsilon':e,'degree':d,'saturated':sat,'area':str(ar)} for a,b,q,e,d,sat,ar in cells],indent=2)+'\n')
print(out, 'cells',len(cells),'middle area',areas)
